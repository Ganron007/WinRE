# Hash budget. A stage is routinely 300-800 MB; hashing all of it is seconds, not
# minutes, but a 5 GB procmon.pml across many packs is not free. Above the cap
# the hash is recorded as absent WITH A REASON — never as a placeholder that
# looks like a hash.
HASH_CAP_BYTES = int(os.environ.get("WINRE_MANIFEST_HASH_CAP",
                                    str(2 * 1024 ** 3)))


def classify(rel: str, stage_name: str | None = None) -> tuple[str, str, str]:
    """(source, domain, kind) for a stage-relative path.

    Unknown files are recorded as `unclassified` rather than dropped: a file we
    do not recognise is exactly the one a reader needs to see.
    """
    p = rel.replace("\\", "/").lower()
    if stage_name in {"quick", "deep", "yara", "report", "intake"}:
        p = stage_name + "/" + p
    # Keep the independent Procmon capture separately attributable inside the
    # deep stage instead of classifying it as a generic deep-stage artifact.
    if p.startswith("deep/debug_monitor/"):
        p = p[len("deep/"):]
    for stage in ("quick", "deep", "yara", "report", "intake"):
        if p.startswith(stage + "/"):
            source = {"quick": "quick_analysis", "deep": "deep_analysis",
                      "yara": "yara", "report": "report",
                      "intake": "intake"}[stage]
            domain = DERIVED if stage in ("report", "yara") else IN_GUEST
            return source, domain, "stage_artifact"
    if p.startswith("dynamic/"):
        p = p[len("dynamic/"):]
    if p in _PATH_MAP:
        return _PATH_MAP[p]
    for prefix, triple in _DIR_MAP.items():
        if p.startswith(prefix):
            return triple
    for name, triple in _PATH_MAP.items():
        if p.endswith("/" + name):
            return triple
    return ("unclassified", IN_GUEST, "unknown")


def _hash(path: Path) -> tuple[str | None, str | None]:
    """sha256 of a file, or (None, reason) when it was not hashed."""
    try:
        size = path.stat().st_size
    except OSError as e:
        return None, f"stat failed: {e}"
    if size > HASH_CAP_BYTES:
        return None, (f"not hashed: {size} B exceeds the "
                      f"{HASH_CAP_BYTES} B cap (WINRE_MANIFEST_HASH_CAP)")
    h = hashlib.sha256()
    try:
        with path.open("rb") as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b""):
                h.update(chunk)
    except OSError as e:
        return None, f"read failed: {e}"
    return h.hexdigest(), None


def _artifact_id(source: str, rel: str, n: int) -> str:
    """Stable, human-readable, unique within the manifest."""
    stem = rel.replace("\\", "/").split("/")[-1]
    stem = "".join(c if c.isalnum() else "-" for c in stem).strip("-")[:40]
    return f"{source}-{n:03d}-{stem or 'file'}"


def build_manifest(stage_dir: Path, *, run_id: str, sha256: str = "",
                   mode: str = "dynamic", requested: dict | None = None,
                   meta: dict | None = None,
                   hash_files: bool = True,
                   include_stage_metadata: bool = False) -> dict:
    """Write `manifest.json` into `stage_dir` and return it.

    `requested` names the sources this run asked for, so a source that was never
    requested is `not_requested` rather than silently missing. `meta` is the
    stage's META.json when present — recorded errors are what turn a source into
    `failed` instead of `partial`.
    """
    stage_dir = Path(stage_dir)
    stage_name = stage_dir.name if stage_dir.name in {
        "dynamic", "quick", "deep", "yara", "report", "intake"} else None
    meta = meta or {}
    requested = requested or {}
    artifacts: list[dict] = []
    seen: dict[str, list[str]] = {}

    all_paths = []
    for p in stage_dir.rglob("*"):
        if not p.is_file() or p.is_symlink():
            continue
        rel = str(p.relative_to(stage_dir)).replace("\\", "/")
        parts = {part.lower() for part in rel.split("/")}
        if parts.intersection({"previous_runs", ".incoming", ".winre-producer",
                               ".winre-staging"}):
            continue
        base = rel.rsplit("/", 1)[-1]
        if base.lower() == "artifact-manifest.json":
            continue
        if base.lower() == "manifest.json" and not include_stage_metadata:
            continue
        if not include_stage_metadata and base in _WRAPPERS:
            continue
        all_paths.append((p, rel))

    paths = [rel for _, rel in all_paths]
    job_meta = _load_json(stage_dir / "META.job.json")
    if not job_meta and (stage_dir / "dynamic" / "META.job.json").is_file():
        job_meta = _load_json(stage_dir / "dynamic" / "META.job.json")
    validations = _validate_sources(stage_dir, requested, meta or {}, job_meta,
                                    paths, run_id=run_id)
    for path, rel in sorted(all_paths, key=lambda item: item[1]):
        source, domain, kind = classify(rel, stage_name)
        digest, why = (_hash(path) if hash_files else (None, "hashing disabled"))
        n = len(seen.get(source, [])) + 1
        seen.setdefault(source, []).append(
            f"{stage_name}/{rel}" if stage_name else rel)
        artifacts.append({
            "id": _artifact_id(source, rel, n),
            "path": rel,
            "sha256": digest,
            "hash_skipped_reason": why,
            "size_bytes": path.stat().st_size,
            "kind": kind,
            "source_domain": domain,
            "source": source,
            "producer": _producer(rel, source, job_meta),
            "run_id": run_id,
            "collection_window": (job_meta.get("window")
                                  if source in {"frida", "procmon", "network",
                                                "memory", "process_snapshot",
                                                "debug_monitor"}
                                  else None),
            "derived_from": _derived_refs(rel, paths),
            "validation": validations.get(source, {}).get("validation")
                if _is_primary_path(source, rel, stage_name) else None,
        })

    coverage = _coverage_v2(seen, requested, meta, stage_dir=stage_dir,
                            job_meta=job_meta, validations=validations,
                            run_id=run_id)
    return {
        "schema": SCHEMA,
        "run_id": run_id,
        "sample_sha256": sha256,
        "mode": mode,
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "stage_dir": str(stage_dir),
        "artifact_count": len(artifacts),
        "sources": sorted({a["source"] for a in artifacts}),
        "coverage": coverage,
        "collector_status": {s: {k: v for k, v in rec.items()
                                 if k not in ("present", "validation")}
                             for s, rec in coverage.items()},
        "artifacts": artifacts,
        "note": ("Coverage describes COLLECTION, not trust: raw evidence is "
                 "untrusted data in every domain. A source recorded as "
                 "complete produced its primary output; it does not mean the "
                 "sample behaved, or that the sample could not have tampered "
                 "with the collector."),
    }


def _coverage(seen: dict[str, list[str]], requested: dict,
              meta: dict) -> dict[str, dict]:
    """Per-source coverage: complete | partial | failed | not_requested.

    The ordering matters. A source that was not requested is `not_requested`
    even if a stray file from it exists; a source that was requested and is
    missing its primary output is `partial` or `failed`, never `complete`.
    """
    errors = (meta.get("errors") or {}) if isinstance(meta, dict) else {}
    out: dict[str, dict] = {}
    for source, expected in _EXPECTED.items():
        present = seen.get(source, [])
        # "was this asked for" — an explicit request wins; otherwise, files from
        # this source being present is the evidence. `source in present` tests
        # for the literal string in a list of PATHS and is always False, which
        # made a source that plainly ran read as `not_requested`.
        was_requested = bool(requested.get(source, bool(present)))
        if not was_requested:
            out[source] = {"status": "not_requested",
                           "reason": "this run did not ask for it"}
            continue
        if not present:
            err = errors.get(source)
            out[source] = ({
                "status": "failed",
                "reason": f"requested but produced nothing: {err}"
                          if err else "requested but produced nothing",
            } if err else {
                "status": "partial",
                "reason": "requested but produced no files",
            })
            continue
        missing = [e for e in expected
                   if not any(p == e or p.startswith(e) for p in present)]
        if missing:
            out[source] = {
                "status": "partial",
                "reason": f"missing primary output: {', '.join(missing)}",
                "present": present[:10],
            }
            continue
        out[source] = {"status": "complete",
                       "reason": "primary output present",
                       "present": present[:10]}
    return out


def _load_json(path: Path) -> dict:
    try:
        value = json.loads(path.read_text(encoding="utf-8-sig", errors="replace"))
        return value if isinstance(value, dict) else {}
    except (OSError, json.JSONDecodeError):
        return {}


def _matches(path: str, expected: str) -> bool:
    p, e = path.replace("\\", "/").lower(), expected.replace("\\", "/").lower()
    if e.endswith("/"):
        return p.startswith(e) or ("/" + e) in ("/" + p)
    return p == e or p.endswith("/" + e)


def _find_path(stage_dir: Path, expected: str) -> Path | None:
    rel = Path(expected.replace("/", os.sep))
    candidates = [stage_dir / rel]
    if expected.startswith(("dynamic/", "quick/", "deep/", "yara/", "report/", "intake/")):
        candidates.append(stage_dir / Path(*rel.parts[1:]))
    else:
        candidates.extend(stage_dir / stage / rel for stage in
                         ("dynamic", "quick", "deep", "yara", "report", "intake"))
    return next((p for p in candidates if p.exists()), None)


def _producer(rel: str, source: str, job_meta: dict) -> dict:
    base = rel.replace("\\", "/").rsplit("/", 1)[-1].lower()
    name, version_key = _PRODUCER_BY_FILE.get(
        base, (f"WinRE source:{source}", None))
    version = job_meta.get(version_key) if version_key else None
    in_guest = source in {"frida", "procmon", "debug_monitor", "memory", "network", "job",
                          "malcat", "x64dbg", "pe_sieve",
                          "hollows_hunter", "process_snapshot"}
    location = ("in_guest" if in_guest else
                "control_plane" if source == "windbg" else
                "control_plane_or_unrecorded")
    return {"name": name, "location": location,
            "version": version,
            "version_status": "recorded" if version else "not_recorded"}


def _derived_refs(rel: str, all_paths: list[str]) -> list[str]:
    base = rel.replace("\\", "/").rsplit("/", 1)[-1].lower()
    refs: list[str] = []
    for target in _DERIVED_FROM.get(base, ()):
        refs.extend(p for p in all_paths
                    if p.lower() == target.lower()
                    or p.lower().endswith("/" + target.lower())
                    or (target.endswith("/") and target.lower() in p.lower()))
    return list(dict.fromkeys(refs))[:100]


def _is_primary_path(source: str, rel: str, stage_name: str | None) -> bool:
    candidate = f"{stage_name}/{rel}" if stage_name else rel
    return any(_matches(candidate, expected)
               for expected in _EXPECTED.get(source, ()))


def _validate_primary(source: str, primary: Path | None) -> dict:
    if primary is None:
        return {"status": "missing", "reason": "primary artifact absent"}
    if primary.is_dir():
        return {"status": "valid", "kind": "directory",
                "file_count": sum(1 for p in primary.rglob("*") if p.is_file())}
    try:
        if source == "frida":
            records = 0
            with primary.open("r", encoding="utf-8", errors="replace") as fh:
                for line in fh:
                    if line.strip():
                        json.loads(line)
                        records += 1
            return {"status": "valid", "kind": "jsonl", "records": records}
        if source == "debug_monitor" and primary.name.lower() == "process_events.jsonl":
            records = 0
            with primary.open("r", encoding="utf-8", errors="replace") as fh:
                for line in fh:
                    if line.strip():
                        json.loads(line)
                        records += 1
            return {"status": "valid" if records else "invalid",
                    "kind": "jsonl", "records": records}
        if source in {"job", "process_snapshot", "malcat", "windbg", "quick_analysis",
                      "deep_analysis", "yara", "report", "intake", "pe_sieve"} \
                and primary.suffix.lower() == ".json":
            json.loads(primary.read_text(encoding="utf-8-sig", errors="replace"))
            return {"status": "valid", "kind": "json"}
        if source in {"procmon", "debug_monitor"} and primary.suffix.lower() == ".csv":
            with primary.open("r", encoding="utf-8-sig", errors="replace",
                              newline="") as fh:
                header = next(csv.reader(fh), [])
            return {"status": "valid" if header else "invalid", "kind": "csv",
                    "columns": len(header)}
        if source in {"network", "external_capture"} \
                and primary.suffix.lower() in (".pcap", ".pcapng"):
            with primary.open("rb") as fh:
                magic = fh.read(4)
            valid = magic in {b"\xd4\xc3\xb2\xa1", b"\xa1\xb2\xc3\xd4",
                              b"\x4d\x3c\xb2\xa1", b"\xa1\xb2\x3c\x4d",
                              b"\x0a\x0d\x0d\x0a"}
            return {"status": "valid" if valid else "invalid", "kind": "pcap",
                    "magic": magic.hex()}
        return {"status": "not_checked", "reason": "no format validator"}
    except Exception as e:
        return {"status": "invalid",
                "reason": f"{type(e).__name__}: {str(e)[:160]}"}


def _stage_terminal(stage_dir: Path, stage: str, run_id: str | None) -> dict:
    root = stage_dir if stage_dir.name == stage else stage_dir / stage
    record = _load_json(root / "STAGE.json") or _load_json(root / "META.json")
    if not record:
        return {"status": "unknown", "reason": f"{stage} terminal record absent"}
    if run_id and record.get("run_id") and record.get("run_id") != run_id:
        return {"status": "failed", "reason": f"{stage} belongs to another run"}
    if record.get("ok") is True:
        return {"status": "completed", "reason": "stage terminal record ok"}
    if record.get("skipped") or record.get("not_applicable"):
        return {"status": "not_applicable",
                "reason": record.get("reason") or record.get("error") or "skipped"}
    if record.get("error"):
        return {"status": "failed", "reason": str(record["error"])[:240]}
    return {"status": "unknown", "reason": "stage terminal status is not affirmative"}


def _terminal(source: str, stage_dir: Path, meta: dict, job: dict,
              run_id: str | None) -> dict:
    explicit_map = meta.get("collector_status") if isinstance(meta, dict) else None
    explicit = explicit_map.get(source) if isinstance(explicit_map, dict) else None
    if isinstance(explicit, dict) and explicit.get("status"):
        return dict(explicit)
    # A primary artifact can survive a collector failure (for example, a
    # truncated trace flushed before Frida exits). Preserve that evidence, but
    # do not treat file presence as proof the requested source completed.
    errors = meta.get("errors") if isinstance(meta, dict) else None
    error = errors.get(source) if isinstance(errors, dict) else None
    if error:
        reason = (error.get("error") or error.get("reason") or str(error)
                  if isinstance(error, dict) else str(error))
        return {"status": "failed", "reason": str(reason)[:240]}
    stage = {"quick_analysis": "quick", "deep_analysis": "deep"}.get(source, source)
    if stage in {"quick", "deep", "yara", "report", "intake"}:
        return _stage_terminal(stage_dir, stage, run_id)
    if source in {"composition", "audit", "pipeline"}:
        filename = {"composition": "composite.json", "audit": "audit.json",
                    "pipeline": "execution_plan.json"}[source]
        path = _find_path(stage_dir, filename)
        record = _load_json(path) if path else {}
        if not record:
            return {"status": "unknown", "reason": f"{filename} absent or unreadable"}
        if run_id and record.get("run_id") and record.get("run_id") != run_id:
            return {"status": "failed", "reason": f"{filename} belongs to another run"}
        if source == "audit" and "truly_green" not in record:
            return {"status": "failed", "reason": "audit terminal fields absent"}
        return {"status": "completed", "reason": f"{filename} recorded"}
    if source == "frida" and job.get("frida_exit") is not None:
        try:
            code = int(job["frida_exit"])
        except (TypeError, ValueError):
            return {"status": "failed", "reason": "Frida exit code malformed"}
        if code != 0:
            return {"status": "failed", "reason": f"Frida exited with {code}"}
        if not (job.get("sample_pid") or meta.get("sample_pid")):
            return {"status": "failed", "reason": "Frida exited without sample PID"}
        return {"status": "completed", "reason": "Frida exited cleanly with sample PID"}
    if source == "procmon" and "procmon_csv" in job:
        return {"status": "completed" if job.get("procmon_csv") else "failed",
                "reason": "Procmon CSV produced" if job.get("procmon_csv") else
                          "Procmon CSV absent at collector shutdown"}
    if source == "debug_monitor":
        record_path = _find_path(stage_dir, "debug_monitor/META.json")
        record = _load_json(record_path) if record_path else {}
        if record.get("run_id") and run_id and record.get("run_id") != run_id:
            return {"status": "failed", "reason": "debug monitor belongs to another run"}
        status = record.get("status")
        if status in {"collected", "failed", "unavailable", "partial"}:
            return {"status": "completed" if status == "collected" else status,
                    "reason": record.get("reason") or
                             f"ETW debug capture status={status}"}
        if record.get("error"):
            return {"status": "failed", "reason": str(record["error"])[:240]}
        return {"status": "unknown", "reason": "debug monitor terminal record absent"}
    if source == "network" and "fakenet_started" in job:
        return {"status": "completed" if job.get("fakenet_started") else "failed",
                "reason": "FakeNet started" if job.get("fakenet_started") else
                          "FakeNet did not start"}
    if source == "network_enrichment":
        ni_path = _find_path(stage_dir, "network_intel.json")
        if ni_path:
            ni = _load_json(ni_path)
            if ni.get("ok") is True:
                return {"status": "completed", "reason": "pcap enrichment completed"}
            return {"status": "failed", "reason": ni.get("error") or
                    ni.get("reason") or "pcap enrichment did not report success"}
        return {"status": "unknown", "reason": "network enrichment record absent"}
    if source == "windbg":
        path = _find_path(stage_dir, "windbg_analysis.json")
        record = _load_json(path) if path else {}
        if record.get("ok") is True:
            return {"status": "completed", "reason": "host-side WinDbg analysis completed"}
        if record.get("skipped"):
            reason = str(record["skipped"])
            if "no dump" in reason.lower():
                return {"status": "not_applicable", "reason": reason}
            return {"status": "unavailable", "reason": reason}
        if record.get("error"):
            return {"status": "failed", "reason": str(record["error"])[:240]}
        return {"status": "unknown", "reason": "host-side WinDbg terminal record absent"}
    if source == "job":
        if job.get("ok") is True:
            return {"status": "completed", "reason": "job terminal record ok"}
        return {"status": "failed", "reason": job.get("error") or "job META not ok"}
    if source == "malcat":
        triage = meta.get("malcat_triage") or job.get("malcat_triage") or {}
        if triage.get("ok") is True:
            return {"status": "completed", "reason": "Malcat triage completed"}
        if meta.get("malcat_skipped"):
            return {"status": "unavailable", "reason": str(meta["malcat_skipped"])[:200]}
        if triage.get("error"):
            return {"status": "failed", "reason": str(triage["error"])[:200]}
    if source == "memory":
        if meta.get("job_timeout") is True:
            return {"status": "partial",
                    "reason": "collection job timed out; memory evidence was not accepted into the current run"}
        if not (job.get("sample_pid") or meta.get("sample_pid")):
            return {"status": "not_applicable", "reason": "no sample process to harvest"}
        pm_path = _find_path(stage_dir, "post_mortem.json")
        pm = _load_json(pm_path) if pm_path else {}
        harvest = pm.get("memory_harvest") or {}
        if harvest.get("status") in {"not_applicable", "not-run"}:
            return {"status": "not_applicable", "reason": harvest.get("reason") or "no applicable dump"}
        if harvest.get("ok") is True:
            return {"status": "completed", "reason": "post-mortem harvest completed"}
    if source == "pe_sieve":
        if not job.get("pe_sieve_enabled"):
            return {"status": "not_requested", "reason": "pe-sieve not enabled"}
        if job.get("pe_sieve_report_valid"):
            return {"status": "completed", "reason": "pe-sieve report validated"}
        if job.get("pe_sieve_ran"):
            return {"status": "failed", "reason": "no valid pe-sieve JSON report"}
    if source == "x64dbg":
        dump = meta.get("x64dbg_dump") or {}
        if dump.get("status") in {"not_applicable", "skipped"}:
            return {"status": "not_applicable", "reason": dump.get("reason") or dump.get("status")}
        if dump.get("attempted"):
            return {"status": "completed" if dump.get("ok") else "failed",
                    "reason": dump.get("reason") or "x64dbg terminal status"}
    if source == "process_snapshot":
        pre = _find_path(stage_dir, "process_snapshot_pre.json")
        post = _find_path(stage_dir, "process_snapshot_post.json")
        if pre and post:
            return {"status": "completed", "reason": "pre/post snapshots produced"}
    if source == "external_capture":
        return {"status": "unknown", "reason": "external collector terminal status not recorded"}
    return {"status": "unknown", "reason": "collector terminal status not recorded"}


def _validate_sources(stage_dir: Path, requested: dict, meta: dict,
                      job_meta: dict, paths: list[str],
                      run_id: str | None = None) -> dict[str, dict]:
    result: dict[str, dict] = {}
    for source, expected in _EXPECTED.items():
        primary = next((_find_path(stage_dir, item) for item in expected
                        if _find_path(stage_dir, item) is not None), None)
        terminal = _terminal(source, stage_dir, meta, job_meta, run_id)
        result[source] = {**terminal,
                          "validation": _validate_primary(source, primary)}
    return result


def _coverage_v2(seen: dict[str, list[str]], requested: dict, meta: dict,
                 *, stage_dir: Path, job_meta: dict, validations: dict,
                 run_id: str | None) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for source, expected in _EXPECTED.items():
        present = seen.get(source, [])
        req = requested.get(source, bool(present))
        if isinstance(req, dict):
            was_requested, required = bool(req.get("requested")), bool(req.get("required"))
        else:
            was_requested, required = bool(req), False
        terminal = validations.get(source) or _terminal(source, stage_dir, meta, job_meta, run_id)
        base = {"requested": was_requested, "required": required,
                "collector_status": terminal.get("status"),
                "collector_reason": terminal.get("reason"),
                "present": present[:10]}
        if not was_requested or terminal.get("status") == "not_requested":
            out[source] = {**base, "status": "not_requested",
                           "reason": terminal.get("reason") or "source was not requested"}
            continue
        if terminal.get("status") in {"unavailable", "not_applicable"}:
            out[source] = {**base, "status": terminal["status"],
                           "reason": terminal.get("reason") or terminal["status"]}
            continue
        if terminal.get("status") == "failed":
            out[source] = {**base, "status": "failed",
                           "reason": terminal.get("reason") or "collector failed",
                           "validation": terminal.get("validation")}
            continue
        missing = [e for e in expected
                   if not any(_matches(p, e) for p in present)
                   and not _expected_directory_exists(stage_dir, e)]
        if missing:
            out[source] = {**base, "status": "partial",
                           "reason": f"missing primary output: {', '.join(missing)}",
                           "validation": terminal.get("validation")}
            continue
        validation = terminal.get("validation") or {}
        if validation.get("status") == "invalid":
            out[source] = {**base, "status": "failed",
                           "reason": "primary artifact failed format validation",
                           "validation": validation}
        elif terminal.get("status") == "completed":
            out[source] = {**base, "status": "complete",
                           "reason": terminal.get("reason") or "collector completed",
                           "validation": validation}
        else:
            out[source] = {**base, "status": "partial",
                           "reason": "artifact exists but collector completion is unverified",
                           "validation": validation}
    return out


def _expected_directory_exists(stage_dir: Path, expected: str) -> bool:
    if not expected.endswith("/"):
        return False
    found = _find_path(stage_dir, expected)
    return bool(found and found.is_dir())


def write_manifest(stage_dir: Path, **kw) -> dict:
    """Build and write; never raises (a manifest failure must not fail a run)."""
    try:
        m = build_manifest(Path(stage_dir), **kw)
        (Path(stage_dir) / "manifest.json").write_text(
            json.dumps(m, indent=2, default=str) + "\n", encoding="utf-8")
        return m
    except Exception as e:                                   # pragma: no cover
        return {"schema": SCHEMA, "ok": False,
                "error": f"{type(e).__name__}: {e}"}


def write_pack_manifests(pack_root: Path, *, run_id: str, sha256: str,
                         mode: str, dynamic_requested: bool) -> dict:
    """Finalize per-stage manifests plus one complete pack inventory.

    Stage manifests are written before audit so requested-source coverage can
    gate the run. The pack inventory is written last, after reports/audit, so
    it hashes the actual delivered view. Historical `previous_runs` are
    deliberately kept outside the current-run inventory.
    """
    pack_root = Path(pack_root)
    dynamic_meta = _load_json(pack_root / "dynamic" / "META.json")
    dynamic_stage = (_load_json(pack_root / "dynamic" / "STAGE.json")
                     or dynamic_meta)
    job_meta = _load_json(pack_root / "dynamic" / "META.job.json")
    dynamic_sources = {
        "frida": {"requested": dynamic_requested, "required": dynamic_requested},
        "procmon": {"requested": dynamic_requested, "required": dynamic_requested},
        "network": {"requested": dynamic_requested, "required": dynamic_requested},
        "network_enrichment": {"requested": dynamic_requested, "required": False},
        "job": {"requested": dynamic_requested, "required": dynamic_requested},
        "process_snapshot": {"requested": dynamic_requested, "required": False},
        "memory": {"requested": dynamic_requested, "required": False},
        "malcat": {"requested": dynamic_requested, "required": False},
        "windbg": {"requested": dynamic_requested, "required": False},
        "pe_sieve": {"requested": bool(dynamic_requested and
                          (job_meta.get("pe_sieve_enabled") or dynamic_meta.get("pe_sieve_ran"))),
                      "required": False},
        "hollows_hunter": {"requested": bool(dynamic_requested and
                               dynamic_meta.get("hollows_hunter_requested")),
                           "required": False},
        "x64dbg": {"requested": bool(dynamic_requested and
                         (mode == "agentic-dbg" or dynamic_meta.get("x64dbg_dump", {}).get("attempted"))),
                   "required": False},
        "external_capture": {"requested": bool(dynamic_meta.get("external_capture_requested")),
                              "required": False},
    }
    static_sources = {
        "intake": {"requested": True, "required": True},
        "quick_analysis": {"requested": True, "required": True},
        "deep_analysis": {"requested": True, "required": True},
        "yara": {"requested": True, "required": True},
        "report": {"requested": True, "required": True},
    }
    debug_monitor_source = {"requested": mode == "agentic-dbg",
                            "required": mode == "agentic-dbg"}
    stage_sources = {
        "intake": {"intake": static_sources["intake"]},
        "quick": {"quick_analysis": static_sources["quick_analysis"]},
        "deep": {"deep_analysis": static_sources["deep_analysis"],
                 "debug_monitor": debug_monitor_source},
        "yara": {"yara": static_sources["yara"]},
        "report": {"report": static_sources["report"]},
        "dynamic": dynamic_sources,
    }
    stage_manifests: dict[str, dict] = {}
    for stage, requests in stage_sources.items():
        stage_dir = pack_root / stage
        if not stage_dir.is_dir():
            continue
        terminal_path = stage_dir / "STAGE.json"
        if not terminal_path.is_file():
            terminal_path = stage_dir / "META.json"
        terminal = _load_json(terminal_path)
        if terminal:
            terminal["run_id"] = run_id
            terminal_path.write_text(json.dumps(terminal, indent=2, default=str) + "\n",
                                     encoding="utf-8")
        source_meta = ((dynamic_meta or dynamic_stage)
                       if stage == "dynamic" else terminal)
        manifest = write_manifest(
            stage_dir, run_id=run_id, sha256=sha256, mode=mode,
            requested=requests, meta=source_meta,
            include_stage_metadata=False)
        stage_manifests[stage] = manifest
        if terminal and terminal_path.name == "STAGE.json":
            terminal["manifest"] = manifest
            terminal_path.write_text(json.dumps(terminal, indent=2, default=str) + "\n",
                                     encoding="utf-8")

    plan = _load_json(pack_root / "execution_plan.json")
    root_requests = {**static_sources, **dynamic_sources,
                     "debug_monitor": debug_monitor_source}
    root_manifest = build_manifest(
        pack_root, run_id=run_id, sha256=sha256, mode=mode,
        requested=root_requests,
        meta={**dynamic_stage, **dynamic_meta, "run_id": run_id},
        include_stage_metadata=True)
    root_manifest["execution_plan"] = {
        "dynamic_requested": dynamic_requested,
        "execution_sites": plan.get("execution_sites") or [],
    }
    (pack_root / "artifact-manifest.json").write_text(
        json.dumps(root_manifest, indent=2, default=str) + "\n", encoding="utf-8")
    return {"ok": True, "run_id": run_id,
            "stage_manifests": stage_manifests,
            "artifact_manifest": root_manifest}


def read_manifest(stage_dir: Path) -> dict:
    p = Path(stage_dir) / "manifest.json"
    if not p.is_file():
        return {}
    try:
        return json.loads(p.read_text(encoding="utf-8-sig"))
    except Exception:
        return {}


def incomplete_sources(stage_dir: Path) -> list[tuple[str, str]]:
    """(source, reason) for every source that is not `complete`.

    This is what a report and the findings plane should consult instead of
    inferring "no file means nothing happened".
    """
    m = read_manifest(stage_dir)
    out = []
    for source, rec in (m.get("coverage") or {}).items():
        if rec.get("status") not in {"complete", "not_requested"}:
            out.append((source, f"{rec.get('status')}: {rec.get('reason', '')}"))
    return sorted(out)
